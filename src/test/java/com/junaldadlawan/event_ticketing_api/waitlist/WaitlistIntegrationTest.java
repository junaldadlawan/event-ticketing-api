    private final List<UUID> createdOrgIds = new ArrayList<>();
    private final List<UUID> createdEventIds = new ArrayList<>();
    private final List<UUID> createdTicketTypeIds = new ArrayList<>();
    private final List<UUID> createdUserIds = new ArrayList<>();
    private final List<UUID> createdWaitlistEntryIds = new ArrayList<>();

    @AfterEach
    void tearDown() {
        for (UUID id : createdWaitlistEntryIds) {
            waitlistEntryRepository.deleteById(id);
        }
        createdWaitlistEntryIds.clear();
        // Sweep any entries the concurrency test created that weren't
        // individually tracked (bulk-generated by concurrent joiners).
        waitlistEntryRepository.findAll().stream()
                .filter(e -> createdEventIds.contains(e.getEventId()))
                .forEach(e -> waitlistEntryRepository.deleteById(e.getId()));
        for (UUID id : createdTicketTypeIds) {
            ticketTypeRepository.deleteById(id);
        }
        createdTicketTypeIds.clear();
        for (UUID id : createdEventIds) {
            eventRepository.deleteById(id);
        }
        createdEventIds.clear();
        for (UUID id : createdOrgIds) {
            organizationRepository.deleteById(id);
        }
        createdOrgIds.clear();
        for (UUID id : createdUserIds) {
            userRepository.deleteById(id);
        }
        createdUserIds.clear();
    }

    private User inMemoryUser(Role role) {
        return User.builder().id(UUID.randomUUID()).email(role.name().toLowerCase() + "-" + UUID.randomUUID() + "@test.local").role(role).build();
    }

    private User persistUser(Role role) {
        User user = User.builder()
                .name("Waitlist Test User")
                .email("waitlist-" + UUID.randomUUID() + "@test.local")
                .passwordHash("irrelevant")
                .role(role)
                .build();
        User saved = userRepository.save(user);
        createdUserIds.add(saved.getId());
        return saved;
    }

    private UUID persistOrganization(UUID ownerId) {
        Organization organization = Organization.builder()
                .name("Waitlist Test Org " + UUID.randomUUID())
                .status(OrganizationStatus.APPROVED)
                .ownerId(ownerId)
                .documents(List.of())
                .build();
        Organization saved = organizationRepository.save(organization);
        createdOrgIds.add(saved.getId());
        return saved.getId();
    }

    private UUID persistEvent(UUID organizationId) {
        Instant startAt = Instant.now().plus(10, ChronoUnit.DAYS);
        Event event = Event.builder()
                .organizationId(organizationId)
                .title("Waitlist Test Event")
                .description("desc")
                .category("music")
                .status(EventStatus.PUBLISHED)
                .ticketPrefix("W" + UUID.randomUUID().toString().substring(0, 2).toUpperCase())
                .startAt(startAt)
                .endAt(startAt.plus(2, ChronoUnit.HOURS))
                .timezone("UTC")
                .build();
        Event saved = eventRepository.save(event);
        createdEventIds.add(saved.getId());
        return saved.getId();
    }

    private UUID persistTicketType(UUID eventId, int quantityAvailable) {
        TicketType tt = TicketType.builder()
                .eventId(eventId)
                .name("GA")
                .kind(TicketTypeKind.GENERAL_ADMISSION)
                .price(Money.builder().amount(1000L).currency("USD").build())
                .quantityTotal(Math.max(quantityAvailable, 1))
                .quantityAvailable(quantityAvailable)
                .saleStartAt(Instant.now().minus(1, ChronoUnit.DAYS))
                .saleEndAt(Instant.now().plus(5, ChronoUnit.DAYS))
                .maxPerOrder(10)
                .build();
        TicketType saved = ticketTypeRepository.save(tt);
        createdTicketTypeIds.add(saved.getId());
        return saved.getId();
    }

    // ---- POST /events/{eventId}/waitlist — sold-out gate (BR-WAIT-001) ----

    @Test
    void join_specificTicketType_soldOut_returns201_withPositionOne() throws Exception {
        UUID orgId = persistOrganization(UUID.randomUUID());
        UUID eventId = persistEvent(orgId);
        UUID ticketTypeId = persistTicketType(eventId, 0);
        User buyer = persistUser(Role.CUSTOMER);
        String token = jwtService.generateAccessToken(buyer);

        mockMvc.perform(post("/api/v1/events/{eventId}/waitlist", eventId)
                        .header("Authorization", "Bearer " + token)
                        .contentType("application/json")
                        .content("{\"ticketTypeId\":\"" + ticketTypeId + "\"}"))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.eventId").value(eventId.toString()))
                .andExpect(jsonPath("$.ticketTypeId").value(ticketTypeId.toString()))
                .andExpect(jsonPath("$.userId").value(buyer.getId().toString()))
                .andExpect(jsonPath("$.position").value(1))
                .andExpect(jsonPath("$.notifiedAt").doesNotExist())
                .andExpect(jsonPath("$.offerExpiresAt").doesNotExist());

        List<WaitlistEntry> rows = waitlistEntryRepository.findAll().stream()
                .filter(e -> e.getEventId().equals(eventId)).toList();
        assertThat(rows).hasSize(1);
        rows.forEach(r -> createdWaitlistEntryIds.add(r.getId()));
    }

