    @Test
    void listMyEntries_returnsOnlyCallersOwnEntries_oldestJoinedFirst() throws Exception {
        UUID orgId = persistOrganization(UUID.randomUUID());
        UUID eventId = persistEvent(orgId);
        UUID ticketTypeAId = persistTicketType(eventId, 0);
        UUID ticketTypeBId = persistTicketType(eventId, 0);
        User caller = persistUser(Role.CUSTOMER);
        User otherUser = persistUser(Role.CUSTOMER);
        String callerToken = jwtService.generateAccessToken(caller);
        String otherToken = jwtService.generateAccessToken(otherUser);

        // Caller joins two different waitlists (oldest first).
        mockMvc.perform(post("/api/v1/events/{eventId}/waitlist", eventId)
                        .header("Authorization", "Bearer " + callerToken)
                        .contentType("application/json")
                        .content("{\"ticketTypeId\":\"" + ticketTypeAId + "\"}"))
                .andExpect(status().isCreated());
        mockMvc.perform(post("/api/v1/events/{eventId}/waitlist", eventId)
                        .header("Authorization", "Bearer " + callerToken)
                        .contentType("application/json")
                        .content("{\"ticketTypeId\":\"" + ticketTypeBId + "\"}"))
                .andExpect(status().isCreated());
        // A different user also joins one of the same waitlists - must never leak into caller's list.
        mockMvc.perform(post("/api/v1/events/{eventId}/waitlist", eventId)
                        .header("Authorization", "Bearer " + otherToken)
                        .contentType("application/json")
                        .content("{\"ticketTypeId\":\"" + ticketTypeAId + "\"}"))
                .andExpect(status().isCreated());

        mockMvc.perform(get("/api/v1/users/me/waitlist-entries")
                        .header("Authorization", "Bearer " + callerToken))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(2))
                .andExpect(jsonPath("$[0].ticketTypeId").value(ticketTypeAId.toString()))
                .andExpect(jsonPath("$[0].userId").value(caller.getId().toString()))
                .andExpect(jsonPath("$[1].ticketTypeId").value(ticketTypeBId.toString()))
                .andExpect(jsonPath("$[1].userId").value(caller.getId().toString()));

        waitlistEntryRepository.findAll().stream()
                .filter(e -> e.getEventId().equals(eventId))
                .forEach(e -> createdWaitlistEntryIds.add(e.getId()));
    }

    // ---- Genuine concurrency: two threads racing to join the SAME (event, ticketType) scope ----

    @Test
    void join_concurrentJoinsForSameScope_neverCollideOnPosition_allPositionsSequentialAndUnique() throws Exception {
        UUID orgId = persistOrganization(UUID.randomUUID());
        UUID eventId = persistEvent(orgId);
        UUID ticketTypeId = persistTicketType(eventId, 0);

        int threadCount = 8;
        List<String> tokens = new ArrayList<>();
        for (int i = 0; i < threadCount; i++) {
            User buyer = persistUser(Role.CUSTOMER);
            tokens.add(jwtService.generateAccessToken(buyer));
        }

        CountDownLatch startLatch = new CountDownLatch(1);
        ExecutorService executor = Executors.newFixedThreadPool(threadCount);
        try {
            List<Callable<Integer>> tasks = IntStream.range(0, threadCount)
                    .<Callable<Integer>>mapToObj(i -> () -> {
                        startLatch.await();
                        return mockMvc.perform(post("/api/v1/events/{eventId}/waitlist", eventId)
                                        .header("Authorization", "Bearer " + tokens.get(i))
                                        .contentType("application/json")
                                        .content("{\"ticketTypeId\":\"" + ticketTypeId + "\"}"))
                                .andReturn().getResponse().getStatus();
                    })
                    .collect(Collectors.toList());

            List<Future<Integer>> futures = tasks.stream().map(executor::submit).collect(Collectors.toList());
            startLatch.countDown();

            List<Integer> statuses = new ArrayList<>();
            for (Future<Integer> f : futures) {
                statuses.add(f.get(30, TimeUnit.SECONDS));
            }
            assertThat(statuses).as("every concurrent join for a brand-new scope must succeed (201), got %s", statuses)
                    .allMatch(status -> status == 201);
        } finally {
            executor.shutdown();
        }

        List<WaitlistEntry> rows = waitlistEntryRepository.findAll().stream()
                .filter(e -> e.getEventId().equals(eventId)).toList();
        rows.forEach(r -> createdWaitlistEntryIds.add(r.getId()));

        assertThat(rows).hasSize(threadCount);
        Set<Integer> positions = rows.stream().map(WaitlistEntry::getPosition).collect(Collectors.toSet());
        assertThat(positions)
                .as("no two concurrent joiners for the same scope may land on the same position (V17 unique index + retry loop)")
                .hasSize(threadCount)
                .isEqualTo(IntStream.rangeClosed(1, threadCount).boxed().collect(Collectors.toSet()));
    }
